/**
 * Table sorting and search run in the browser as anywidget modules. The
 * plugin bundle has node-only imports the browser can't load, so each widget's
 * source is embedded here as a string and written next to the bundle at build
 * time.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";

const HEADER = "// Generated by myst-listing (src/widgets.ts); do not edit.\n";

const SORT_SOURCE = HEADER + `export default {
  render({ model }) {
    const columns = model.get("columns");
    const orders = model.get("orders"); // "column:dir" -> sorted row order, computed at build (plugin.ts)
    const firstDirection = model.get("firstDirection") || []; // first-click direction per column: text 1 (A-Z), numbers/dates -1
    const root = document.querySelector(".myst-listing-sort-" + model.get("id"));
    // Header cells live in the light DOM and survive effect re-runs; wire once.
    if (!root || root.dataset.mystSortWired) return;
    root.dataset.mystSortWired = "1";

    // Data rows in build order: the entries in orders point into this list.
    const rows = Array.from(root.querySelectorAll("tr.myst-listing-item"));

    // The hover/focus arrow reveal needs a stylesheet (inline styles can't
    // express :hover), added once per page.
    if (!document.querySelector("style[data-myst-listing-sort]")) {
      const style = document.createElement("style");
      style.dataset.mystListingSort = "1";
      style.textContent = [
        // Arrows visible at rest so readers can tell the table is sortable.
        ".myst-sort-arrow{display:inline-block;width:1em;margin-left:0.2em;opacity:0.35;transition:opacity 0.15s;}",
        "th:hover>.myst-sort-arrow,th:focus-visible>.myst-sort-arrow{opacity:0.7;}",
        "th[aria-sort]>.myst-sort-arrow{opacity:1;}",
        // Grey-with-alpha tint reads on light and dark themes; :has scopes it
        // to sortable headers so other tables on the page are untouched.
        "th:has(>.myst-sort-arrow):hover{background:rgba(128,128,128,0.12);}",
        // Keep the arrow on the same line as the header text in narrow columns.
        "th:has(>.myst-sort-arrow){white-space:nowrap;}",
      ].join("");
      document.head.append(style);
    }

    const ths = Array.from(root.querySelectorAll("th"));
    let current = null;
    let dir = 1;
    ths.forEach((th, i) => {
      const col = columns[i];
      const arrow = document.createElement("span");
      arrow.className = "myst-sort-arrow";
      arrow.textContent = "⇅";
      th.appendChild(arrow);
      th.style.cursor = "pointer";
      // Keyboard-focusable, keeping the implicit columnheader role: aria-sort
      // is only announced on column headers.
      th.tabIndex = 0;
      const activate = () => {
        dir = current === col ? -dir : firstDirection[i] || 1;
        current = col;
        ths.forEach((h) => h.removeAttribute("aria-sort"));
        th.setAttribute("aria-sort", dir === 1 ? "ascending" : "descending");
        root.querySelectorAll(".myst-sort-arrow").forEach((s) => (s.textContent = "⇅"));
        arrow.textContent = dir === 1 ? "↑" : "↓";
        // appendChild moves existing nodes, so this reorders in place.
        (orders[col + ":" + dir] || []).forEach((r) => rows[r] && rows[r].parentNode.appendChild(rows[r]));
      };
      th.addEventListener("click", activate);
      th.addEventListener("keydown", (e) => {
        if (e.key === "Enter" || e.key === " ") {
          e.preventDefault();
          activate();
        }
      });
    });
  },
};
`;

const SEARCH_SOURCE = HEADER + `export default {
  render({ model, el }) {
    const root = document.querySelector(".myst-listing-search-" + model.get("id"));
    if (!root || el.querySelector("input")) return;
    // Every built-in display marks its items with myst-listing-item, but the
    // theme only keeps that class on div, span, and table rows. Gallery cards
    // are matched by the theme's own .myst-card class, and list bullets by
    // position: the list display's <ul> is this root's direct child.
    const ITEMS = ".myst-listing-item, .myst-listing-gallery .myst-card, :scope > ul > li";
    // One param for every searchable listing on the page, so readers can link
    // to a filtered view.
    const PARAM = "search";

    // The theme renders the widget in a shadow root, so this stylesheet only
    // reaches the widget. Transparent background and inherited color keep it
    // readable on dark themes; greys with alpha read on both.
    el.innerHTML = [
      "<style>",
      ".box{position:relative;max-width:24rem;margin:0 0 1rem;}",
      "input{display:block;width:100%;box-sizing:border-box;padding:0.45rem 2rem 0.45rem 0.7rem;",
      "font:inherit;font-size:0.9rem;color:inherit;background:transparent;",
      "border:1px solid rgba(128,128,128,0.5);border-radius:6px;}",
      "input::-webkit-search-cancel-button{display:none;}", // ours below, so every browser gets one
      "button{position:absolute;right:0.25rem;top:50%;transform:translateY(-50%);",
      "border:0;background:none;color:inherit;opacity:0.6;cursor:pointer;font-size:1.1rem;line-height:1;padding:0.2rem 0.45rem;}",
      "button:hover,button:focus-visible{opacity:1;}",
      "[role=status]{margin:0 0 1rem;opacity:0.6;font-size:0.9rem;}",
      "</style>",
      '<div class="box">',
      '<input type="search" placeholder="Search…" autocomplete="off" aria-label="Search this listing">',
      '<button type="button" aria-label="Clear search" hidden>×</button>',
      "</div>",
      '<div role="status" hidden>No matches.</div>',
    ].join("");
    const input = el.querySelector("input");
    const clear = el.querySelector("button");
    const empty = el.querySelector("[role=status]");

    // Hiding sets the item's inline display, which the item wrappers in
    // display.ts are built to tolerate. An item shows only when every typed
    // word appears in its text.
    const apply = () => {
      const words = input.value.toLowerCase().split(/\\s+/).filter(Boolean);
      let shown = 0;
      for (const item of root.querySelectorAll(ITEMS)) {
        const text = item.textContent.toLowerCase();
        const show = words.every((w) => text.includes(w));
        item.style.display = show ? "" : "none";
        if (show) shown++;
      }
      clear.hidden = !input.value;
      empty.hidden = shown > 0;
    };
    const update = () => {
      apply();
      const url = new URL(location.href);
      if (input.value) url.searchParams.set(PARAM, input.value);
      else url.searchParams.delete(PARAM);
      history.replaceState(history.state, "", url);
    };
    input.addEventListener("input", update);
    clear.addEventListener("click", () => {
      input.value = "";
      update();
      input.focus();
    });

    input.value = new URL(location.href).searchParams.get(PARAM) || "";
    if (input.value) apply();
  },
};
`;

const here = dirname(fileURLToPath(import.meta.url));

/** Write a widget module next to the bundle and return its page-relative path
 * for the anywidget `esm` field. Skip the write when the file already matches,
 * because MyST hashes assets by mtime and a rewrite would duplicate the asset on
 * every build. URL-loaded plugins work too, because mystmd caches them inside
 * the project's _build. */
function widgetEsm(name: string, source: string, vfile: any): string {
  const file = join(here, `myst-listing-${name}.mjs`);
  if (!existsSync(file) || readFileSync(file, "utf-8") !== source) writeFileSync(file, source);
  // Forward slashes even on Windows: this is a URL path, not a file path.
  return relative(dirname(vfile.path), file).split("\\").join("/");
}

export const sortWidgetEsm = (vfile: any) => widgetEsm("sort", SORT_SOURCE, vfile);
export const searchWidgetEsm = (vfile: any) => widgetEsm("search", SEARCH_SOURCE, vfile);
